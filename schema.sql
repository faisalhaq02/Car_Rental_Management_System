CREATE TABLE CUSTOMER (
    CustomerID INT PRIMARY KEY AUTO_INCREMENT,
    Name VARCHAR(100) NOT NULL,
    Email VARCHAR(100) UNIQUE NOT NULL,
    Street VARCHAR(100),
    City VARCHAR(50),
    Postal_Code VARCHAR(10)
);

-- CUSTOMER_CONTACT Table (Updated with Auto-Incremented ContactID)
CREATE TABLE CUSTOMER_CONTACT (
    ContactID INT PRIMARY KEY AUTO_INCREMENT,
    CustomerID INT,
    Contact_Number VARCHAR(15) NOT NULL UNIQUE,
    FOREIGN KEY (CustomerID) REFERENCES CUSTOMER(CustomerID) ON DELETE CASCADE
);

-- DEALER Table
CREATE TABLE DEALER (
    D_id INT PRIMARY KEY AUTO_INCREMENT,
    Name VARCHAR(100) NOT NULL,
    Street VARCHAR(100),
    City VARCHAR(50),
    Province VARCHAR(50),
    Postal_Code VARCHAR(10)
);

-- CAR Table (Added Constraints for Year, Rental Price, and Availability)
CREATE TABLE CAR (
    Car_id INT PRIMARY KEY AUTO_INCREMENT,
    Vehicle_id VARCHAR(50) UNIQUE NOT NULL,
    Make VARCHAR(100) NOT NULL,
    Model VARCHAR(100) NOT NULL,
    Year INT CHECK (Year BETWEEN 1950 AND 2050),  -- Fixed range
    Rental_price DECIMAL(10,2) CHECK (Rental_price >= 0.01), 
    Availability ENUM('Available', 'Rented') DEFAULT 'Available'
);


-- LUXURY_CAR Table (1:1 with CAR)
CREATE TABLE LUXURY_CAR (
    Car_id INT PRIMARY KEY,
    FOREIGN KEY (Car_id) REFERENCES CAR(Car_id) ON DELETE CASCADE
);

-- FEATURES Master Table
CREATE TABLE FEATURES (
    FeatureID INT PRIMARY KEY AUTO_INCREMENT,
    Feature_Name VARCHAR(100) UNIQUE NOT NULL
);

-- LUXURY_FEATURES Table (Updated to Use FeatureID)
CREATE TABLE LUXURY_FEATURES (
    Car_id INT,
    FeatureID INT,
    PRIMARY KEY (Car_id, FeatureID),
    FOREIGN KEY (Car_id) REFERENCES LUXURY_CAR(Car_id) ON DELETE CASCADE,
    FOREIGN KEY (FeatureID) REFERENCES FEATURES(FeatureID) ON DELETE CASCADE
);

-- ECONOMY_CAR Table (1:1 with CAR)
CREATE TABLE ECONOMY_CAR (
    Car_id INT PRIMARY KEY,
    Fuel_Efficiency DECIMAL(5,2) CHECK (Fuel_Efficiency > 0),
    FOREIGN KEY (Car_id) REFERENCES CAR(Car_id) ON DELETE CASCADE
);

-- MAINTENANCE Table (1:1 with CAR)
CREATE TABLE MAINTENANCE (
    M_id INT PRIMARY KEY AUTO_INCREMENT,
    Car_id INT UNIQUE, -- Ensuring 1:1 relationship
    Date DATE NOT NULL,
    Description TEXT NOT NULL,
    Cost DECIMAL(10,2) CHECK (Cost >= 0),
    FOREIGN KEY (Car_id) REFERENCES CAR(Car_id) ON DELETE CASCADE
);

-- RESERVATION Table (Added Status Column)
CREATE TABLE RESERVATION (
    Reservation_id INT PRIMARY KEY AUTO_INCREMENT,
    Start_date DATE NOT NULL,
    End_date DATE NOT NULL,
    Total_amount DECIMAL(10,2) CHECK (Total_amount >= 0),
    Customer_id INT,
    Status ENUM('Pending', 'Confirmed', 'Cancelled', 'Completed') DEFAULT 'Pending',
    FOREIGN KEY (Customer_id) REFERENCES CUSTOMER(CustomerID) ON DELETE CASCADE,
    CHECK (End_date > Start_date)
);

-- RENTSELLS Table (Added Transaction_Type Column)
CREATE TABLE RENTSELLS (
    D_id INT,
    Car_id INT,
    Transaction_Type ENUM('Rent', 'Sell') NOT NULL,
    PRIMARY KEY (D_id, Car_id),
    FOREIGN KEY (D_id) REFERENCES DEALER(D_id) ON DELETE CASCADE,
    FOREIGN KEY (Car_id) REFERENCES CAR(Car_id) ON DELETE CASCADE
);

-- RESERVES Table (1:M with CUSTOMER and CAR)
CREATE TABLE RESERVES (
    CustomerID INT,
    CarID INT,
    PRIMARY KEY (CustomerID, CarID),
    FOREIGN KEY (CustomerID) REFERENCES CUSTOMER(CustomerID) ON DELETE CASCADE,
    FOREIGN KEY (CarID) REFERENCES CAR(Car_id) ON DELETE CASCADE
);

-- INQUIRE Table (1:M with CUSTOMER and CAR)
CREATE TABLE INQUIRE (
    CustomerID INT,
    CarID INT,
    PRIMARY KEY (CustomerID, CarID),
    FOREIGN KEY (CustomerID) REFERENCES CUSTOMER(CustomerID) ON DELETE CASCADE,
    FOREIGN KEY (CarID) REFERENCES CAR(Car_id) ON DELETE CASCADE
);

-- MAKES Table (Added Constraint for Reservation_Date)
CREATE TABLE MAKES (
    CustomerID INT,
    ReservationID INT,
    Reservation_Date DATE NOT NULL,
    PRIMARY KEY (CustomerID, ReservationID),
    FOREIGN KEY (CustomerID) REFERENCES CUSTOMER(CustomerID) ON DELETE CASCADE,
    FOREIGN KEY (ReservationID) REFERENCES RESERVATION(Reservation_id) ON DELETE CASCADE
);

